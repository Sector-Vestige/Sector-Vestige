using System.Linq;
using Content.Client._SV.Cargo.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._SV.Licences;
using Content.Shared.Cargo.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Prototypes;

namespace Content.Client.Cargo.UI
{
    public sealed partial class CargoConsoleMenu : FancyWindow
    {
        public List<ProtoId<LicencePrototype>> LicenceCatalogue = new();

        public event Action<LicenceProductRow>? OnLicenceSelected;

        private IEnumerable<LicencePrototype> LicencePrototypes =>
            _protoManager.EnumeratePrototypes<LicencePrototype>();


        public void PopulateLicences()
        {
            Licences.RemoveAllChildren();
            var licences = LicencePrototypes.ToList();

            licences.Sort((x, y) =>
                string.Compare(x.Name, y.Name, StringComparison.CurrentCultureIgnoreCase));

            var search = SearchBar.Text.Trim().ToLowerInvariant();
            foreach (var prototype in licences)
            {
                if (search.Length == 0 && _category == null ||
                    search.Length != 0 && prototype.Name.ToLowerInvariant().Contains(search) ||
                    search.Length != 0 && prototype.Description.ToLowerInvariant().Contains(search))
                {
                    var button = new LicenceProductRow
                    {
                        Licence = prototype,
                        LicenceName = { Text = prototype.Name },
                        LicenceDescription = { Text = prototype.Description },
                        MainButton = { ToolTip = prototype.Description },
                        Icon = { Texture = _spriteSystem.Frame0(prototype.Icon)}
                    };
                    button.MainButton.OnPressed += _ =>
                    {
                        OnLicenceSelected?.Invoke(button);
                    };
                    Licences.AddChild(button);
                }
            }
        }
    }
}
